const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const { stripTypeScriptTypes } = require('node:module');
const context = vm.createContext({});
vm.runInContext(stripTypeScriptTypes(fs.readFileSync('lib/speech.ts','utf8').replace(/export /g, '') + '\nglobalThis.api = {matchSpokenOption, readableSpeech};'), context);
const { matchSpokenOption: match, readableSpeech: read } = context.api;
const options = ['Gato', 'PÃO', '8', 'Árvore'];
assert.equal(match('gato.', options), 'Gato');
assert.equal(match('pao', options), 'PÃO');
assert.equal(match('oito', options), '8');
assert.equal(match('Minha resposta é árvore!', options), 'Árvore');
for (const [spoken, expected] of [['alternativa A','Gato'],['letra bê','PÃO'],['opção C','8'],['D','Árvore'],['opção quatro','Árvore']]) assert.equal(match(spoken, options), expected);
assert.equal(match('dois', ['2','4','6','8']), '2', 'Spoken number must match answer content rather than position');
assert.equal(match('alternativa dois', ['2','4','6','8']), '4');
assert.equal(match('A', ['B','A','D','C']), 'A', 'Exact letter answer has priority for literacy exercises');
assert.equal(match('gato ou árvore', options), null, 'Ambiguous speech must not choose an answer');
assert.equal(match('alternativa E', options), null);
assert.equal(match('', options), null);
assert.equal(match('', ['?', 'casa', 'bola', 'gato']), null, 'Silence cannot match punctuation');
assert.equal(match('ponto de interrogação', ['?', '.', ',', '!']), '?');
assert.equal(match('vírgula', ['?', '.', ',', '!']), ',');
assert.equal(match('talvez seja um gato', options), null, 'Do not guess with substring matching');
assert.equal(read('?'), 'ponto de interrogação');
assert.equal(read('!'), 'ponto de exclamação');
assert.equal(read('3 × 4 = 12'), '3  vezes  4  igual a  12');
assert(read('8 ÷ 2').includes('dividido por'));
assert.equal(read('1/2'), '1 sobre 2');
assert.equal(read('6 - 2'), '6 menos 2');
assert.equal(read('pt-BR'), 'pt-BR');
assert.equal((read('● ● ●').match(/pedra/g) || []).length, 3);
console.log('Speech verified: accents, numbers, option labels, exact literacy answers, ambiguous input rejection, and spoken mathematical symbols.');
